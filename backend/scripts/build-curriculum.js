#!/usr/bin/env node
// Generates docs/CURRICULUM.md (the human-readable lesson plan) straight from
// the lesson files, so the plan can never drift from what the site teaches.
//   npm run curriculum
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { UNITS, LESSONS, TOTAL_DAYS, LESSON_ORDER } from '../content/index.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const out = path.join(__dirname, '..', '..', 'docs', 'CURRICULUM.md');

const words = (html = '') => html.replace(/<[^>]+>/g, ' ').split(/\s+/).filter(Boolean).length;
function lessonWords(l) {
  return l.steps.reduce((n, s) => n + words(s.html) + words(s.caption) + (s.cards || []).reduce((m, c) => m + words(c.back), 0), 0);
}
const TOOL_STEPS = new Set(['widget', 'diagram']);
const PRACTICE = new Set(['check', 'truefalse', 'numeric', 'match', 'order']);

let md = '';
const totalMinutes = LESSON_ORDER.reduce((n, id) => n + LESSONS.get(id).lesson.minutes, 0);
const totalWords = LESSON_ORDER.reduce((n, id) => n + lessonWords(LESSONS.get(id).lesson), 0);
const totalQuiz = LESSON_ORDER.reduce((n, id) => { const s = LESSONS.get(id).lesson.steps; return n + s[s.length - 1].questions.length; }, 0);
const totalPractice = LESSON_ORDER.reduce((n, id) => n + LESSONS.get(id).lesson.steps.filter((s) => PRACTICE.has(s.type)).length, 0);

md += `# TradeIQ Curriculum\n\n`;
md += `_Generated by \`npm run curriculum\` from \`backend/content/\`. Don't edit by hand._\n\n`;
md += `| | |\n|---|---|\n`;
md += `| Units | ${UNITS.length} |\n| Lessons | ${LESSON_ORDER.length} |\n| Suggested schedule | ${TOTAL_DAYS} days (about 2 lessons a day, plus one exam day per unit) |\n`;
md += `| Lesson time | about ${Math.round(totalMinutes / 60)} hours |\n| Teaching text | about ${totalWords.toLocaleString()} words |\n`;
md += `| Practice questions inside lessons | ${totalPractice} |\n| End-of-lesson quiz questions | ${totalQuiz} |\n`;
md += `| Unit final exam question pool | ${UNITS.reduce((n, u) => n + u.chapters.reduce((m, c) => m + (c.bossQuestions || []).length, 0), 0)} |\n\n`;
md += `Each lesson is a sequence of one-screen steps (reading, flip cards, diagrams, interactive tools, practice questions) ending in a 5-question quiz. Passing (60%+) earns XP and extends the daily streak. Each unit ends with a 15-question "final boss" exam drawn from that unit's question pool (70% to pass).\n\n`;

for (const u of UNITS) {
  const lessons = u.chapters.flatMap((c) => c.lessons);
  md += `---\n\n## Unit ${u.number}: ${u.title}\n\n*${u.subtitle}.* ${lessons.length} lessons, about ${Math.round(lessons.reduce((n, l) => n + l.minutes, 0) / 60)} hours.\n\n`;
  u.chapters.forEach((c, ci) => {
    md += `### Chapter ${ci + 1}: ${c.title}\n\n${c.blurb}\n\n| Day | Lesson | Min | What you'll learn | Interactive tools |\n|---|---|---|---|---|\n`;
    for (const l of c.lessons) {
      const tools = l.steps.filter((s) => TOOL_STEPS.has(s.type)).map((s) => s.name);
      md += `| ${LESSONS.get(l.id).day} | **${l.title}** | ${l.minutes} | ${l.summary.replace(/\|/g, '/')} | ${[...new Set(tools)].join(', ') || '—'} |\n`;
    }
    md += '\n';
  });
  md += `**Day ${u.examDay}: ${u.title} Final Boss exam.** 15 questions from all ${u.chapters.length} chapters. Unlocks after every lesson in the unit is passed.\n\n`;
}

fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, md);
console.log(`Wrote ${path.relative(process.cwd(), out)} (${LESSON_ORDER.length} lessons, ${TOTAL_DAYS} days)`);
